function subjectCatalogKey(subject = '') {
  const s = String(subject || '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, ' ');
  if (!s) return '';
  if (s === 'math' || s === 'mathematics') return 'maths';
  if (s === 'sst' || s === 'social studies') return 'social science';
  if (s === 'physics' || s === 'chemistry' || s === 'biology') return 'science';
  return s;
}

export function canonicalCbseNcertTopics(classLabel = '', subject = '', board = '') {
  const boardKey = String(board || '')
    .toUpperCase()
    .replace(/[\s/\\-]+/g, '');
  if (boardKey.includes('IIT') || boardKey.includes('NEET') || boardKey.includes('JEE')) {
    return [];
  }
  if (boardKey && boardKey !== 'CBSE' && boardKey !== 'CBSC') {
    return [];
  }
  const classNumber = String(classLabel || '').match(/(\d+)/)?.[1] || '';
  const subjectKey = subjectCatalogKey(subject);
  if (!classNumber || !subjectKey) return [];
  return [...(CBSE_NCERT_TOPICS[classNumber]?.[subjectKey] || [])];
}
